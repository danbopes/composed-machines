#!/usr/bin/env python3
"""Render RESULTS.md from results/*.jsonl (latest 3600-tick entry per save)
and results/*.census.json. Hand-written interpretation lives in
RESULTS.notes.md and is appended verbatim, so a rerun keeps it.
"""
import json
import subprocess
from pathlib import Path

from benchlib import BENCH, RESULTS
from make_save import COMPOSED, NATIVE_MATRIX, PAIRS

TICKS = 3600


def latest(name):
    p = RESULTS / f"{name}.jsonl"
    if not p.exists():
        return None
    rows = [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
    rows = [r for r in rows if r["ticks"] == TICKS]
    return rows[-1] if rows else None


def best_run(r):
    return min(r["per_run"], key=lambda x: x["mean_ms"])


def cat(r, k):
    return r["best_categories_ms"].get(k, 0.0)


def top_classes(r, n=4):
    c = r["best_categories_ms"]
    rows = sorted(((k, v) for k, v in c.items() if k[:1].isupper()), key=lambda kv: -kv[1])
    return ", ".join(f"{k} {v:.3f}" for k, v in rows[:n] if v >= 0.0005)


HEAD = ("| save | runs | mean (best run) | min tick | median tick | p95 tick | spread | "
        "entityUpdate | scriptUpdate | luaGC | top per-class |\n|---|---|---|---|---|---|---|---|---|---|---|")


def row(label, r):
    b = best_run(r)
    return (f"| {label} | {r['runs']} | {r['best_mean_ms']:.3f} | {b['min_tick_ms']:.3f} | "
            f"{b['median_ms']:.3f} | {b['p95_ms']:.3f} | {r['spread_pct']}% | "
            f"{cat(r, 'entityUpdate'):.3f} | {cat(r, 'scriptUpdate'):.3f} | "
            f"{cat(r, 'luaGarbageIncremental'):.3f} | {top_classes(r)} |")


def per_instance(r, empty, n):
    """ns per instance per tick: whole-update delta over the empty world, and
    the entity+script+GC delta."""
    whole = (r["best_mean_ms"] - empty["best_mean_ms"]) / n * 1e6
    parts = ("entityUpdate", "scriptUpdate", "luaGarbageIncremental")
    es = sum(cat(r, k) - cat(empty, k) for k in parts) / n * 1e6
    return whole, es


def main():
    out = []
    allr = [latest(p.stem) for p in sorted(RESULTS.glob("*.jsonl"))]
    allr = [r for r in allr if r]
    cpu = subprocess.run(["sh", "-c", "lscpu | sed -n 's/^Model name: *//p'"],
                         capture_output=True, text=True).stdout.strip()
    loads = [x for r in allr for x in (r["loadavg_before"][0], r.get("loadavg_after", [0])[0])]
    pins = sorted({r.get("cpus") or "none" for r in allr})
    out.append("# Benchmark results: composed machine emulation vs native, mulark maps, pY\n")
    out.append("Generated by `report.py` from `results/*.jsonl` (raw JSON lines kept there) "
               "and `results/*.census.json`. Rerun everything with `./measure.sh`.\n")
    out.append(f"- Hardware: {cpu}, 16 threads, 60 GB; Factorio 2.1.24 headless `--benchmark`.")
    out.append(f"- Pinning: `taskset -c {', '.join(pins)}` (logical CPUs 8-11 = second threads "
               "of physical cores 0-3).")
    out.append(f"- {TICKS} ticks per run; the first ticks of each run are dropped from the per-tick "
               "stats (`skip` 300, 600 for mulark). ms per update unless noted.")
    if loads:
        out.append(f"- 1-minute load average sampled before/after each benchmark: "
                   f"{min(loads):.2f} to {max(loads):.2f}.")
    out.append("- 'mean (best run)' is the lowest per-run mean (interference only adds time); "
               "min/median/p95 are per-tick figures from that run; spread is the range of "
               "per-run means. Per-class columns are Factorio's own per-entity-class timers.\n")

    empty = latest("empty-0")
    out.append("## (a) Native matrix\n")
    out.append(HEAD)
    if empty:
        out.append(row("empty (baseline)", empty))
    for n in (2000, 20000):
        for v in NATIVE_MATRIX:
            r = latest(f"{v}-{n}")
            if r:
                out.append(row(f"{v} N={n}", r))
    if empty:
        out.append("\nPer instance (ns per tick, delta over the empty world):\n")
        out.append("| variant | N=2000 whole | N=2000 entity+script+GC | N=20000 whole | N=20000 entity+script+GC |")
        out.append("|---|---|---|---|---|")
        for v in NATIVE_MATRIX:
            cells = []
            for n in (2000, 20000):
                r = latest(f"{v}-{n}")
                cells += [f"{x:.1f}" for x in per_instance(r, empty, n)] if r else ["-", "-"]
            out.append(f"| {v} | " + " | ".join(cells) + " |")

    out.append("\n## (b) Composed (component-lab emulation) vs native, N = 2000\n")
    out.append(HEAD)
    for v in COMPOSED:
        for name in [v] + PAIRS[v]:
            r = latest(f"{name}-2000")
            if r:
                out.append(row(name, r))
    if empty:
        out.append("\nPer instance, ns per tick (delta over the empty world, divided by N = 2000). "
                   "'whole' is wholeUpdate; 'e+s+gc' is entityUpdate + scriptUpdate + "
                   "luaGarbageIncremental. Ratio = composed / native on 'whole'.\n")
        out.append("| composed | native comparison | composed whole | native whole | ratio | "
                   "composed e+s+gc | native e+s+gc | composed scriptUpdate ns |")
        out.append("|---|---|---|---|---|---|---|---|")
        for v in COMPOSED:
            c = latest(f"{v}-2000")
            if not c:
                continue
            cw, ces = per_instance(c, empty, 2000)
            cs = (cat(c, "scriptUpdate") - cat(empty, "scriptUpdate")) / 2000 * 1e6
            for nat in PAIRS[v]:
                r = latest(f"{nat}-2000")
                if not r:
                    continue
                nw, nes = per_instance(r, empty, 2000)
                ratio = f"{cw / nw:.2f}" if nw > 0.5 else "n/a (native ~0)"
                out.append(f"| {v} | {nat} | {cw:.1f} | {nw:.1f} | {ratio} | {ces:.1f} | {nes:.1f} | {cs:.1f} |")

    out.append("\n## (c) mulark's public maps\n")
    out.append(HEAD)
    manifest = json.loads((BENCH / "saves/mulark/manifest.json").read_text())
    for fname, m in manifest.items():
        r = latest(Path(fname).stem.replace(" ", "_"))
        if r:
            out.append(row(f"{Path(fname).stem} ({m.get('map_version', '?')})", r))
        elif not m.get("loads_on_2_1_24"):
            out.append(f"| {Path(fname).stem} | - | does not load: {m.get('load_error', '')} |||||||||")

    out.append("\n## (d) pY saves\n")
    out.append(HEAD)
    py = ["pY_134", "pY_Season_3_A2_Fixed", "pY_Fixed"]
    for n in py:
        r = latest(n)
        if r:
            out.append(row(f"{n} ({r['mods']} mods)", r))
    out.append("\nOther script-relevant columns (best run, ms/tick):\n")
    out.append("| save | scriptUpdate | luaGC | trains | controlBehavior | electricNetwork | fluidFlow | transportLines |")
    out.append("|---|---|---|---|---|---|---|---|")
    for n in py:
        r = latest(n)
        if r:
            ks = ["scriptUpdate", "luaGarbageIncremental", "trains", "controlBehaviorUpdate",
                  "electricNetworkUpdate", "fluidFlowUpdate", "transportLinesUpdate"]
            out.append(f"| {n} | " + " | ".join(f"{cat(r, k):.3f}" for k in ks) + " |")
    cens = {n: json.loads((RESULTS / f"{n}.census.json").read_text())
            for n in py if (RESULTS / f"{n}.census.json").exists()}
    if cens:
        out.append("\nInstance counts of the Lua-composed families (see ../research/pyanodons.md), "
                   "counted by a census mod added for one benchmark tick (saves not modified):\n")
        out.append("| family | part | " + " | ".join(cens) + " |")
        out.append("|---|---|" + "---|" * len(cens))
        fams = next(iter(cens.values()))["families"]
        for fam, parts in fams.items():
            for label in parts:
                vals = [str(c["families"][fam][label]["count"]) for c in cens.values()]
                out.append(f"| {fam} | {label} | " + " | ".join(vals) + " |")
        out.append("| all entities | | " + " | ".join(str(c["entities_total"]) for c in cens.values()) + " |")
        out.append("| scriptUpdate ms/tick | | " + " | ".join(
            f"{cat(latest(n), 'scriptUpdate'):.3f}" if latest(n) else "-" for n in cens) + " |")

    notes = BENCH / "RESULTS.notes.md"
    if notes.exists():
        out.append("\n" + notes.read_text())
    print("\n".join(out))


if __name__ == "__main__":
    main()
